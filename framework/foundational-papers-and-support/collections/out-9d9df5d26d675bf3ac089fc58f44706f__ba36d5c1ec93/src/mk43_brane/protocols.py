from typing import Protocol, Iterable, Sequence
from .models import *

class Module5Base(Protocol):
    version:str; contract_version:str; internal_dimension:int; canonical_state_policy:str; rewrite_policy:str; domain_ids:tuple[str,...]
    def dimension_model(self)->dict[str,bool]: ...
    def fork_request_context(self): ...
    def canonical_fingerprint(self)->str: ...
    def healthcheck(self)->bool: ...

class AI5(Module5Base,Protocol):
    def interpret(self,request:RuntimeRequest)->RecoveryIntent: ...
    def rank(self,candidates:Sequence[EdgeRecord],context:dict)->Sequence[EdgeRecord]: ...
    def continue_or_terminate(self,node:TraversalNode,edge:EdgeRecord,intent:RecoveryIntent,context:dict)->str: ...
    def place_continuation(self,node:TraversalNode,edge:EdgeRecord,realization:TraversalRealization)->None: ...
    def collapse(self,graph:CanonicalGraph,intent:RecoveryIntent)->TraversalRealization: ...
    def validate_collapse(self,realization:TraversalRealization,graph:CanonicalGraph)->None: ...

class API5(Module5Base,Protocol):
    def resolve(self,subject:str)->str: ...
    def neighbors(self,handle:str,direction:TraversalDirection)->Sequence[EdgeRecord]: ...
    def recover_closure(self,root:str,intent:RecoveryIntent)->CanonicalGraph: ...
    def recover_equations(self,handle:str)->Sequence[str]: ...
    def recover_provenance(self,handle:str)->Sequence[str]: ...
    def resolve_chirality(self,node:TraversalNode,intent:RecoveryIntent,provenance:Sequence[str])->str: ...
    def admissible(self,node:TraversalNode,intent:RecoveryIntent,chirality:str,provenance:Sequence[str])->bool: ...
    def validate_graph(self,graph:CanonicalGraph)->None: ...

class Library5(Module5Base,Protocol):
    def recover(self,handle:str,context:Realization6Coordinate,language:str)->KnowledgePackage: ...
    def recover_equations(self,handle:str,context:Realization6Coordinate,language:str)->Sequence[KnowledgeChunk]: ...
    def recover_models(self,handle:str,context:Realization6Coordinate,language:str)->Sequence[KnowledgeChunk]: ...
    def recover_analogies(self,handle:str,context:Realization6Coordinate,language:str)->Sequence[KnowledgeChunk]: ...
    def recover_explanations(self,handle:str,context:Realization6Coordinate,language:str)->Sequence[KnowledgeChunk]: ...
    def assemble_chunk(self,handle:str,context:Realization6Coordinate,language:str)->KnowledgePackage: ...
    def recover_batch(self,handles:Iterable[tuple[str,Realization6Coordinate]],language:str)->list[KnowledgePackage]: ...
