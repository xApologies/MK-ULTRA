#!/usr/bin/env python3
import sqlite3,json,urllib.parse
from pathlib import Path
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
DB=Path(__file__).resolve().parent.parent/"database"/"R55_DUAL_CARRIER_PROVENANCE.sqlite"
def cx():
 c=sqlite3.connect(DB);c.row_factory=sqlite3.Row;return c
def rr(x):return [dict(r) for r in x.fetchall()]
class H(BaseHTTPRequestHandler):
 def out(self,x):
  b=json.dumps(x,indent=2).encode();self.send_response(200);self.send_header("Content-Type","application/json");self.send_header("Content-Length",str(len(b)));self.end_headers();self.wfile.write(b)
 def do_GET(self):
  p=urllib.parse.urlparse(self.path).path;c=cx()
  try:
   if p=="/":return self.out({"terminal":"@open/populate_hidden_carrier_binding_record","state":"DUAL_CRAWL_CLOSURE"})
   if p=="/stats":return self.out(rr(c.execute("select * from crawl_stats")))
   if p=="/fields":return self.out(rr(c.execute("select * from binding_fields")))
   if p=="/debts":return self.out(rr(c.execute("select * from debts")))
   if p=="/roadblocks":return self.out(rr(c.execute("select * from roadblocks")))
   return self.out({"error":"not found"})
  finally:c.close()
if __name__=="__main__":ThreadingHTTPServer(("127.0.0.1",8791),H).serve_forever()
